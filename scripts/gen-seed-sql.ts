// Generates supabase/seed.sql from the bundled sample data.
import { writeFileSync } from 'node:fs';
import { SEED_OPPORTUNITIES } from '../src/data/seed';
import { oppToRow } from '../src/data/remote-map';

const q = (v: unknown) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const cols = ['id', 'kind', 'scope', 'sector', 'title', 'provider', 'summary', 'criteria', 'details', 'deadline', 'source_url', 'source_label', 'published_on', 'status', 'sample'] as const;

const rows = SEED_OPPORTUNITIES.map((o) => {
  const r = oppToRow(o);
  return `(${[q(r.id), q(r.kind), q(r.scope), q(r.sector), q(r.title), q(r.provider), q(r.summary), j(r.criteria), j(r.details),
    q(r.deadline), q(r.source_url), q(r.source_label), q(r.published_on), q(r.status === 'verified' ? 'in-review' : r.status), 'true'].join(', ')})`;
});

const sql = `-- SAMPLE DATA, NOT VERIFIED. Generated by scripts/gen-seed-sql.ts. Run after 001_init.sql.
-- Every row is sample = true, so it is shown with an "unverified" badge and cannot be marked verified.
insert into public.opportunities (${cols.join(', ')}) values
${rows.join(',\n')}
on conflict (id) do nothing;
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Wrote ${rows.length} rows`);
